  Widget _profileCard(PlanProfile profile, bool dense) {
    final selected = _profileId == profile.id;
    final accent = profile.isOffline
        ? ClassicTheme.secondaryAccent
        : ClassicTheme.primaryAccent;

    return InkWell(
      onTap: () => _applyProfile(profile),
      borderRadius: BorderRadius.circular(DS.radiusMd),
      child: Container(
        padding: const EdgeInsets.all(DS.space3),
        decoration: BoxDecoration(
          color:
              selected ? accent.withValues(alpha: 0.12) : context.sunkenSurface,
          borderRadius: BorderRadius.circular(DS.radiusMd),
          border: Border.all(
              color: selected ? accent : context.borderColor,
              width: selected ? 2 : 1),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          mainAxisSize: MainAxisSize.min,
          children: [
            Row(
              children: [
                Icon(
                  profile.isOffline
                      ? Icons.wifi_off_rounded
                      : Icons.cloud_done_rounded,
                  size: 18,
                  color: accent,
                ),
                const SizedBox(width: DS.space2),
                Expanded(
                  child: Text(profile.label,
                      style: TextStyle(
                          fontSize: DS.fontBody,
                          fontWeight: FontWeight.w700,
                          color: context.textPrimary),
                      overflow: TextOverflow.ellipsis),
                ),
                if (selected)
                  Icon(Icons.check_circle_rounded, size: 18, color: accent),
              ],
            ),
            const SizedBox(height: DS.space2),
            Flexible(
              child: Text(
                profile.description,
                style: TextStyle(
                    fontSize: DS.fontMicro,
                    color: context.textSecondary,
                    height: 1.4),
                maxLines: dense ? 2 : 4,
                overflow: TextOverflow.ellipsis,
              ),
            ),
          ],
        ),
      ),
    );
  }

