/// What each tenant is allowed to do.
///
/// The one place a switch is flipped. It must be impossible to save a
/// configuration the app will refuse to run, so:
///
///  * Toggles are generated from [FeatureCatalog], grouped by tier. Basic tiers
///    have no switch; only add-ons do.
///  * Storage mode is a separate control. Choosing an offline mode hides the
///    online tiers entirely and pins devices and outlets to one.
///  * Turning a feature off turns its dependants off, and the rows say why.
///    Turning a feature on whose parent is off is not possible; the row says
///    what to switch on first.
///  * A storage-mode change is **requested**, not applied. The tenant's owner
///    completes it on their own device; until then the store keeps running on
///    its current mode. See FEATURE_MASTER_PLAN.md §9.
///  * A preview strip shows exactly which dashboard cards the owner will see,
///    generated by the same resolver the app uses.
class AdminFeaturesView extends ConsumerStatefulWidget {
  const AdminFeaturesView({super.key});

  @override
  ConsumerState<AdminFeaturesView> createState() => _AdminFeaturesViewState();
}

class _AdminFeaturesViewState extends ConsumerState<AdminFeaturesView> {
  String? _selectedOrgId;
  String _selectedOrgName = '';
  bool _isLoadingOrg = false;
  bool _isSaving = false;
  bool _dirty = false;

  Map<String, bool> _features = {};
  int _maxDevices = 1;
  int _maxOutlets = 1;
  String _profileId = PlanProfile.connected.id;

  /// The mode the store is running on right now.
  String _liveStorageMode = StorageModes.cloudSync;

  /// The mode being configured. Differs from live only while a change is
  /// requested but not yet completed by the owner.
  String _targetStorageMode = StorageModes.cloudSync;

  /// `organizations/{orgId}.pendingStorageChange`, if any.
  Map<String, dynamic>? _pending;

  bool get _targetIsOffline => StorageModes.isOffline(_targetStorageMode);
  bool get _modeChangeRequested => _targetStorageMode != _liveStorageMode;

  // ───────────────────────────────────────────────────────────── data

  Future<void> _loadTenant(String orgId, String orgName) async {
    setState(() {
      _selectedOrgId = orgId;
      _selectedOrgName = orgName;
      _isLoadingOrg = true;
      _dirty = false;
    });

    try {
      final fs = FirebaseFirestore.instance;
      final licDoc = await fs.collection('licenses').doc(orgId).get();
      final orgDoc = await fs.collection('organizations').doc(orgId).get();
      final lic = licDoc.data();
      final org = orgDoc.data();

      // Legacy mirror, read only while documents predating this console exist.
      Map<String, dynamic>? legacy;
      if (lic == null || lic['features'] == null) {
        final featDoc = await fs.collection('features').doc(orgId).get();
        legacy = featDoc.data();
      }

      final profileId =
          (lic?['planProfile'] ?? legacy?['planProfile'])?.toString();
      final profile = profileId != null
          ? PlanProfile.byId(profileId)
          : PlanProfile.forTier(lic?['planTier']?.toString());

      final resolved = <String, bool>{}..addAll(profile.features);
      final raw = lic?['features'] ?? legacy?['features'];
      if (raw is Map) {
        for (final e in raw.entries) {
          resolved[e.key.toString()] = e.value == true;
        }
      }

      final live = (org?['storageMode'] ?? profile.storageMode).toString();
      final pending = org?['pendingStorageChange'];

      _features = resolved;
      _profileId = profile.id;
      _maxDevices = _readInt(lic?['maxDevices'], profile.maxDevices);
      _maxOutlets = _readInt(lic?['maxFranchises'], profile.maxOutlets);
      _liveStorageMode = live.toUpperCase();
      _pending = pending is Map ? Map<String, dynamic>.from(pending) : null;
      _targetStorageMode = (_pending != null && _pending!['status'] == 'PENDING')
          ? (_pending!['to'] ?? live).toString().toUpperCase()
          : _liveStorageMode;
      _applyHardConstraints();
    } catch (e) {
      if (mounted) AppToast.showError(context, 'Could not read this store: $e');
    } finally {
      if (mounted) setState(() => _isLoadingOrg = false);
    }
  }

  static int _readInt(dynamic v, int fallback) {
    if (v is num && v > 0) return v.toInt();
    return fallback;
  }

  /// Whatever the operator clicks, an offline target ends up with one device,
  /// one outlet and nothing that needs the cloud or a second screen.
  void _applyHardConstraints() {
    if (_targetIsOffline) {
      _maxDevices = 1;
      _maxOutlets = 1;
      for (final def in FeatureCatalog.all) {
        if (def.need != FeatureNeed.none || def.tier.isOnline) {
          _features[def.key] = false;
        }
      }
    } else {
      // Online basic ships with every online plan.
      for (final def in FeatureCatalog.byTier(CommercialTier.onlineBasic)) {
        _features[def.key] = true;
      }
      if (_maxDevices <= 1) {
        for (final def in FeatureCatalog.all) {
          if (def.need == FeatureNeed.secondDevice) _features[def.key] = false;
        }
      }
    }
    // Offline basic is always on, and the legacy flag mirrors the mode.
    for (final def in FeatureCatalog.byTier(CommercialTier.offlineBasic)) {
      _features[def.key] = true;
    }
    _features[FeatureKeys.pureOfflineMode] = _targetIsOffline;
    _cascadeOff();
  }

  /// A dependant can never be on while its parent is off.
  void _cascadeOff() {
    var changed = true;
    while (changed) {
      changed = false;
      for (final def in FeatureCatalog.all) {
        if (_features[def.key] != true) continue;
        for (final dep in def.dependsOn) {
          if (_features[dep] != true) {
            _features[def.key] = false;
            changed = true;
            break;
          }
        }
      }
    }
  }

  void _applyProfile(PlanProfile profile) {
    setState(() {
      _profileId = profile.id;
      _features = Map<String, bool>.from(profile.features);
      _maxDevices = profile.maxDevices;
      _maxOutlets = profile.maxOutlets;
      _targetStorageMode = profile.storageMode;
      _applyHardConstraints();
      _dirty = true;
    });
    AppToast.showSuccess(
      context,
      '${profile.label} loaded into the editor',
      subtitle: 'Nothing is live until you save.',
    );
  }

  void _setTargetMode(String mode) {
    setState(() {
      _targetStorageMode = mode;
      _applyHardConstraints();
      _dirty = true;
    });
  }

  void _toggle(String key, bool value) {
    setState(() {
      _features[key] = value;
      if (!value) {
        for (final k in FeatureCatalog.dependants(key)) {
          _features[k] = false;
        }
      }
      _dirty = true;
    });
  }

  /// The resolver's view of what is being configured, for the preview strip.
  Entitlements _preview() {
    final license = SaasLicense(
      planTier: _profileId,
      planProfile: _profileId,
      status: 'ACTIVE',
      maxFranchises: _maxOutlets,
      maxUsers: 99,
      maxDevices: _maxDevices,
      features: Map<String, bool>.from(_features),
      startDate: DateTime.now(),
      endDate: DateTime.now().add(const Duration(days: 365)),
    );
    return Entitlements.fromLicense(license, storageMode: _targetStorageMode);
  }

  Future<void> _save() async {
    final orgId = _selectedOrgId;
    if (orgId == null) return;
    setState(() => _isSaving = true);

    try {
      _applyHardConstraints();
      final fs = FirebaseFirestore.instance;
      final now = FieldValue.serverTimestamp();
      final batch = fs.batch();

      // The authority.
      batch.set(fs.collection('licenses').doc(orgId), {
        'features': _features,
        'planProfile': _profileId,
        'maxDevices': _maxDevices,
        'maxFranchises': _maxOutlets,
        'updatedAt': now,
      }, SetOptions(merge: true));

      // Legacy mirror — one more release.
      batch.set(fs.collection('features').doc(orgId), {
        'features': _features,
        'planProfile': _profileId,
        'updatedAt': now,
        'updatedBy': 'master_admin',
      }, SetOptions(merge: true));

      // A storage-mode change is requested, never applied here. The owner
      // completes provisioning and migration on their device; the mode flips
      // there, after verification. Nothing about the store's current data
      // path changes at this save.
      if (_modeChangeRequested) {
        batch.set(fs.collection('organizations').doc(orgId), {
          'pendingStorageChange': {
            'from': _liveStorageMode,
            'to': _targetStorageMode,
            'status': 'PENDING',
            'requestedBy': 'master_admin',
            'requestedAt': now,
            'steps': <String, dynamic>{},
          },
          'updatedAt': now,
        }, SetOptions(merge: true));
      }

      // The guest-facing web menu reads these two flags and nothing else about
      // the plan, so it can show "not taking orders online" the moment an
      // add-on is switched off — without redeploying the site.
      final preview = _preview();
      batch.set(fs.collection('public_stores').doc(orgId), {
        'onlineMenuEnabled': preview.isEnabled(FeatureKeys.onlineMenu),
        'onlineOrderingEnabled': preview.isEnabled(FeatureKeys.onlineOrderingEnabled),
        'qrOrderingEnabled': preview.isEnabled(FeatureKeys.qrOrdering),
        'entitlementsUpdatedAt': now,
      }, SetOptions(merge: true));

      final enabled = _features.entries
          .where((e) => e.value)
          .map((e) => e.key)
          .toList()
        ..sort();

      batch.set(fs.collection('audit_logs').doc(), {
        'action': 'FEATURES_UPDATED',
        'targetOrgId': orgId,
        'targetOrgName': _selectedOrgName,
        'details': 'Plan $_profileId · mode $_liveStorageMode'
            '${_modeChangeRequested ? ' → $_targetStorageMode (requested)' : ''}'
            ' · $_maxDevices device(s), $_maxOutlets outlet(s) · on: '
            '${enabled.join(', ')}',
        'by': 'master_admin',
        'timestamp': now,
      });

      await batch.commit();

      if (mounted) {
        setState(() {
          _dirty = false;
          if (_modeChangeRequested) {
            _pending = {
              'from': _liveStorageMode,
              'to': _targetStorageMode,
              'status': 'PENDING',
            };
          }
        });
        AppToast.showSuccess(
          context,
          'Saved',
          subtitle: _modeChangeRequested
              ? 'The owner will be asked to complete the storage change at '
                  'their next sign-in.'
              : 'Tills pick this up on their next sync.',
        );
      }
    } catch (e) {
      if (mounted) AppToast.showError(context, 'Could not save: $e');
    } finally {
      if (mounted) setState(() => _isSaving = false);
    }
  }

  Future<void> _cancelPendingChange() async {
    final orgId = _selectedOrgId;
    if (orgId == null) return;
    try {
      await FirebaseFirestore.instance
          .collection('organizations')
          .doc(orgId)
          .set({
        'pendingStorageChange': FieldValue.delete(),
        'updatedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
      if (mounted) {
        setState(() {
          _pending = null;
          _targetStorageMode = _liveStorageMode;
          _applyHardConstraints();
          _dirty = false;
        });
        AppToast.showSuccess(context, 'Storage change cancelled',
            subtitle: 'The store stays on $_liveStorageMode.');
      }
    } catch (e) {
      if (mounted) AppToast.showError(context, 'Could not cancel: $e');
    }
  }

  // ───────────────────────────────────────────────────────────── build

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<QuerySnapshot>(
      stream: FirebaseFirestore.instance.collection('organizations').snapshots(),
      builder: (context, orgSnap) {
        final List<QueryDocumentSnapshot<Object?>> orgDocs =
            orgSnap.data?.docs ?? const <QueryDocumentSnapshot<Object?>>[];

        if (_selectedOrgId == null && orgDocs.isNotEmpty) {
          final first = orgDocs.first;
          final firstData = first.data() as Map<String, dynamic>;
          WidgetsBinding.instance.addPostFrameCallback((_) {
            if (mounted && _selectedOrgId == null) {
              _loadTenant(first.id, (firstData['name'] ?? first.id).toString());
            }
          });
        }

        final compact = context.isCompactScreen;
        final gutter = context.pageGutter;

        return Column(
          children: [
            Expanded(
              child: ListView(
                padding: EdgeInsets.fromLTRB(gutter, gutter, gutter, DS.space10),
                children: [
                  _header(orgDocs, compact),
                  const SizedBox(height: DS.space5),
                  if (_selectedOrgId == null)
                    _emptyState()
                  else if (_isLoadingOrg)
                    const Padding(
                      padding: EdgeInsets.symmetric(vertical: DS.space10),
                      child: Center(child: CircularProgressIndicator()),
                    )
                  else ...[
                    if (_pending != null && _pending!['status'] != 'DONE')
                      _pendingBanner(),
                    _profileSection(),
                    const SizedBox(height: DS.space5),
                    _storageSection(),
                    const SizedBox(height: DS.space5),
                    _limitsSection(),
                    const SizedBox(height: DS.space5),
                    ..._featureSections(),
                    _previewSection(),
                  ],
                ],
              ),
            ),
            if (_selectedOrgId != null && !_isLoadingOrg) _saveBar(),
          ],
        );
      },
    );
  }

