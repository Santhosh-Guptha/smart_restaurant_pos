  Widget _featureRow(FeatureDef def) {
    final on = !def.isAddOn || (_features[def.key] ?? false);
    final missingDep = def.dependsOn
        .where((d) => _features[d] != true)
        .map((d) => FeatureCatalog.find(d)?.label ?? d)
        .toList();
    final blockedByDep = def.isAddOn && !on && missingDep.isNotEmpty;
    final blockedByDevices = def.need == FeatureNeed.secondDevice &&
        _maxDevices <= 1 &&
        !_targetIsOffline;

    String note = def.description;
    Color noteColor = context.textSecondary;
    if (blockedByDevices) {
      note = 'Needs a second device — raise the device count first.';
      noteColor = context.warningColor;
    } else if (blockedByDep) {
      note = 'Needs ${missingDep.join(' and ')} switched on first.';
      noteColor = context.warningColor;
    }

    return Padding(
      padding: const EdgeInsets.symmetric(vertical: DS.space1),
      child: Row(
        children: [
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(def.label,
                    style: TextStyle(
                        fontSize: DS.fontBody,
                        fontWeight: FontWeight.w600,
                        color: context.textPrimary)),
                const SizedBox(height: 2),
                Text(note,
                    style: TextStyle(
                        fontSize: DS.fontMicro, color: noteColor, height: 1.4)),
              ],
            ),
          ),
          const SizedBox(width: DS.space3),
          if (def.isAddOn)
            Switch.adaptive(
              value: on,
              onChanged: (blockedByDep || blockedByDevices)
                  ? null
                  : (v) => _toggle(def.key, v),
            )
          else
            Icon(Icons.check_rounded, color: context.successColor, size: 20),
        ],
      ),
    );
  }

